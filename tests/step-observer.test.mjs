import assert from 'node:assert/strict';
import {StepObserver} from '../static/step-observer.mjs';
const s=new StepObserver(),dt=.01;
const tick=(y,clearance,force,enabled=true)=>s.update('L',{y,clearance,force},dt,enabled);
for(let i=0;i<100;i++)tick(-i*.001,0,10);
assert.equal(s.snapshot().L.steps,0,'Sliding on the ground is not a step');
for(let i=0;i<7;i++)tick(-.1-i*.002,.004,0);
tick(-.12,0,10);
assert.equal(s.snapshot().L.steps,1,'A sustained lift followed by a forward landing counts once');
tick(-.12,0,10);assert.equal(s.snapshot().L.steps,1);
for(let i=0;i<2;i++)tick(-.13,.004,0);tick(-.14,0,10);
assert.equal(s.snapshot().L.steps,1,'Brief contact chatter must not create a step');
for(let i=0;i<7;i++)tick(-.14,.004,0);tick(-.14,0,10);
assert.equal(s.snapshot().L.steps,1,'Vertical bouncing is not forward stepping');
for(let i=0;i<7;i++)tick(-.15,.004,0);tick(-.16,0,10,false);
assert.equal(s.snapshot().L.steps,1,'Falls must not count as landings');
const airborne=new StepObserver();for(let i=0;i<10;i++)airborne.update('R',{y:-.02,clearance:.01,force:0},dt,true);
airborne.update('R',{y:-.04,clearance:0,force:10},dt,true);
assert.equal(airborne.snapshot().R.steps,0,'Initial drop needs an established takeoff to count');
console.log('Step observer: sliding, airborne duration, forward advance, duplicate contacts, falls and initial drop: PASS');
